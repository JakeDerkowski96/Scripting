"""Write the scan into an Obsidian vault as markdown notes.

Layout inside the vault:

    Dashboard.md        regenerated on every run (table of every repo)
    Follow-ups.md       created once if missing, never touched again
    Repos/<name>.md     one note per repo

A repo note has generated parts and human parts. The generated parts are the
frontmatter keys in `OWNED_KEYS` and the block between `START` and `END`; both
are rewritten on every run. Everything else (your notes, decisions, extra
frontmatter keys) is preserved, so re-running is safe.

Required permissions: write access to the vault folder. Nothing else is read
or changed.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from repo_radar.attention import FLAGS
from repo_radar.models import Project, ScanResult
from repo_radar.query import humanize_age, pr_summary, sort_projects, sync_summary

START = "<!-- repo-radar:start -->"
END = "<!-- repo-radar:end -->"
OWNED_KEYS = (
    "type",
    "stage",
    "visibility",
    "branch",
    "sync",
    "open_prs",
    "ci",
    "last_commit",
    "flags",
    "scanned",
)
REPOS_DIR = "Repos"
DASHBOARD = "Dashboard.md"
FOLLOW_UPS = "Follow-ups.md"

_FOLLOW_UPS_TEMPLATE = """# Follow-ups

Things that need doing across the repos. This note is yours; repo-radar never rewrites it.

- [ ]
"""

_NOTE_TAIL = """
## Notes

## Decisions
"""


@dataclass(frozen=True)
class WriteAction:
    """One file the export created, changed or left alone."""

    path: Path
    verb: str  # created | updated | unchanged


def _yaml(value: object) -> str:
    """Return `value` as a YAML flow scalar; JSON is a valid subset."""
    return json.dumps(value, ensure_ascii=False)


def frontmatter_values(project: Project, scanned: datetime) -> dict[str, str]:
    """Return the generated frontmatter keys as ready-to-write YAML values."""
    gh = project.github
    return {
        "type": _yaml("repo"),
        "stage": _yaml(project.meta.stage or "unset"),
        "visibility": _yaml(gh.visibility if gh and gh.visibility else "unknown"),
        "branch": _yaml(project.git.branch),
        "sync": _yaml(sync_summary(project)),
        "open_prs": _yaml(gh.open_prs if gh and gh.open_prs is not None else None),
        "ci": _yaml(gh.ci_status if gh and gh.ci_status else None),
        "last_commit": _yaml(project.git.last_commit[:10] or None),
        "flags": _yaml(project.flags),
        "scanned": _yaml(scanned.strftime("%Y-%m-%d %H:%M")),
    }


def _cell(text: str) -> str:
    """Make `text` safe inside a markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ")


def render_block(project: Project, now: datetime) -> str:
    """Return the generated block, markers included."""
    gh = project.github
    git = project.git
    meta = project.meta
    visibility = gh.visibility if gh and gh.visibility else "unknown"
    if meta.visibility:
        visibility += f" (expected {meta.visibility})"
    last = (
        f"{humanize_age(git.last_commit, now)} ago: {git.last_subject}" if git.last_commit else "—"
    )
    rows = [
        ("Stage", meta.stage or "unset"),
        ("Visibility", visibility),
        ("Branch", f"{git.branch or '—'}, sync {sync_summary(project)}"),
        ("Last commit", last),
        ("Open PRs", pr_summary(project)),
        ("CI", (gh.ci_status if gh and gh.ci_status else "—")),
        ("GitHub", gh.slug if gh and gh.slug else "no remote"),
    ]
    lines = [
        START,
        f"> Generated by repo-radar on {now:%Y-%m-%d %H:%M}. Edit outside this block.",
        "",
    ]
    if meta.summary:
        lines += [meta.summary, ""]
    lines += ["| | |", "|---|---|", *(f"| {k} | {_cell(v)} |" for k, v in rows), ""]
    if meta.next_step:
        lines.append(f"**Next step:** {meta.next_step}")
    if meta.blockers:
        lines.append("**Blockers:** " + "; ".join(meta.blockers))
    if project.flags:
        lines += ["", "**Needs attention**", ""]
        lines += [f"- `{f}`: {FLAGS.get(f, f)}" for f in project.flags]
    lines.append(END)
    return "\n".join(lines)


def _split_frontmatter(text: str) -> tuple[list[str], str]:
    """Return (frontmatter lines, body); no frontmatter gives ([], text)."""
    if not text.startswith("---\n"):
        return [], text
    end = text.find("\n---\n", 3)
    if end == -1:
        return [], text
    return text[4:end].split("\n"), text[end + 5 :]


def merge_note(existing: str | None, project: Project, now: datetime) -> str:
    """Return the note text with generated parts refreshed and human parts kept."""
    values = frontmatter_values(project, now)
    block = render_block(project, now)
    if existing is None:
        head = "\n".join(f"{k}: {v}" for k, v in values.items())
        return f"---\n{head}\n---\n# {project.name}\n\n{block}\n{_NOTE_TAIL}"

    text = existing.replace("\r\n", "\n")
    fm_lines, body = _split_frontmatter(text)
    kept = [ln for ln in fm_lines if ln.split(":", 1)[0].strip() not in OWNED_KEYS]
    fresh = [f"{k}: {v}" for k, v in values.items()]
    head = "\n".join([*fresh, *[ln for ln in kept if ln.strip()]])

    start, end = body.find(START), body.find(END)
    if start != -1 and end > start:
        body = body[:start] + block + body[end + len(END) :]
    else:
        body = body.rstrip("\n") + f"\n\n{block}\n"
    return f"---\n{head}\n---\n{body}"


def render_dashboard(result: ScanResult, projects: list[Project], now: datetime) -> str:
    """Return the Dashboard note: counts, a table of every repo, and what needs attention."""
    ordered = sort_projects(projects, "attention")
    flagged = [p for p in ordered if p.flags]
    lines = [
        "---",
        'type: "dashboard"',
        f"scanned: {_yaml(now.strftime('%Y-%m-%d %H:%M'))}",
        "---",
        "# Repo dashboard",
        "",
        f"Generated by repo-radar on {now:%Y-%m-%d %H:%M} from `{result.root}`. "
        "This note is rewritten on every run; put your own items in [[Follow-ups]].",
        "",
        f"**{len(projects)}** repos, **{len(flagged)}** needing attention.",
        "",
        "| Repo | Stage | Visibility | Sync | PRs | CI | Flags |",
        "|---|---|---|---|---|---|---|",
    ]
    for p in ordered:
        gh = p.github
        lines.append(
            "| "
            + " | ".join(
                [
                    f"[[{REPOS_DIR}/{p.name}\\|{p.name}]]",
                    p.meta.stage or "unset",
                    gh.visibility if gh and gh.visibility else "—",
                    _cell(sync_summary(p)),
                    pr_summary(p),
                    gh.ci_status if gh and gh.ci_status else "—",
                    ", ".join(f"`{f}`" for f in p.flags) or "—",
                ]
            )
            + " |"
        )
    return "\n".join(lines) + "\n"


def _write(path: Path, text: str, *, dry_run: bool) -> WriteAction:
    """Write `text` (LF endings) unless unchanged; report what happened."""
    old = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.is_file() else None
    if old == text:
        return WriteAction(path, "unchanged")
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        # bytes, so Windows does not turn LF into CRLF and show a diff every run
        path.write_bytes(text.encode("utf-8"))
    return WriteAction(path, "created" if old is None else "updated")


def export(
    vault: Path,
    result: ScanResult,
    projects: list[Project],
    now: datetime,
    *,
    dry_run: bool = False,
) -> list[WriteAction]:
    """Write the dashboard and one note per project into `vault`.

    Args:
        vault: Vault folder; created if missing (unless dry_run).
        result: The scan the projects came from.
        projects: Projects to export (already filtered by the caller).
        now: Timestamp stamped into the generated parts.
        dry_run: Report what would change without writing.
    """
    actions: list[WriteAction] = []
    for project in projects:
        path = vault / REPOS_DIR / f"{project.name}.md"
        existing = path.read_text(encoding="utf-8") if path.is_file() else None
        actions.append(_write(path, merge_note(existing, project, now), dry_run=dry_run))
    actions.append(
        _write(vault / DASHBOARD, render_dashboard(result, projects, now), dry_run=dry_run)
    )
    follow = vault / FOLLOW_UPS
    if not follow.exists():
        actions.append(_write(follow, _FOLLOW_UPS_TEMPLATE, dry_run=dry_run))
    return actions
